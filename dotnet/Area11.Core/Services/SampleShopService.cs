                {
                    date = stamp,
                    method,
                    amount,
                    customerId = payer.Id,
                    userId = _user.Id,
                    note = "Khata collection - " + payer.Name
                });

            payer.Balance -= amount;

            if (string.Equals(method, "cash", StringComparison.Ordinal))
            {
                _cashIn += amount;
            }
        }

