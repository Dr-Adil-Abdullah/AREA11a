        private void WriteDay(int daysAgo)
        {
            _cashIn = 0;
            _cashOut = 0;

            WriteShortDatedDelivery(daysAgo);
            RestockIfDeliveryDay(daysAgo);
            SettleOldPurchases(daysAgo);
            WriteBills(daysAgo);
            MaybeReturn(daysAgo);
            PayPendingExpenses(daysAgo);
            WritePlannedExpenses(daysAgo);
            CollectKhata(daysAgo);
            WritePlannedSupplierReturn(daysAgo);
            WritePlannedWriteOff(daysAgo);
            WritePlannedStockTake(daysAgo);
            WritePlannedDrawing(daysAgo);
            WriteShift(daysAgo);
        }

        private long DrawerNow => _float + _cashIn - _cashOut;

        /// <summary>Never let the sample spend money the drawer does not have - that is not a demo, that is a fault.</summary>
        private bool CanSpend(long amount) => DrawerNow >= amount + 200000L;

        // ---------------------------------------------------------------- stock coming in

        private void WriteOpeningPurchase()
        {
            for (var supplierIndex = 0; supplierIndex < Suppliers.Length; supplierIndex++)
            {
                var lines = new List<PurchaseLine>();

                for (var index = 0; index < Products.Length; index++)
                {
                    var product = Products[index];

                    if (product.Supplier != supplierIndex)
                    {
                        continue;
                    }

                    var cover = product.Opening > 0
                        ? product.Opening
                        : product.Typical >= 10 ? product.Typical * 24 : product.Typical * 8;

                    lines.Add(new PurchaseLine { ProductIndex = index, Qty = cover, ExpiryDays = 300 + _rng.Next(400) });

                    // A short-dated bottle the supplier pushed on the shop at the opening: it is
                    // inside its last month from the first day, so the counter never sells it and it
                    // is still on the shelf - expired - at the end of the story. That is the shelf the
                    // expiry alert is about.
                    if (index == 12)
                    {
                        lines.Add(new PurchaseLine
                        {
                            ProductIndex = index, Qty = 6, ExpiryDays = -50, Capture = "expired"
                        });
                    }
                }

                WritePurchase(supplierIndex, lines, HistoryDays, payNow: false);
            }
        }

        /// <summary>
        /// The two lots the story needs a handle on: the near-expiry bottles that came in last week,
        /// and the strips that were short-dated from the day they arrived.
        ///
        /// Why they arrive late instead of on the opening day: the counter never sells a batch that is
        /// inside its last month, but two months ago those batches still had months to run - so a
        /// "short-dated lot" placed on the first day would have been sold like any other and the story
        /// would lose the expired shelf it is meant to show.
        /// </summary>
        private void WriteShortDatedDelivery(int daysAgo)
        {
            if (daysAgo == 60)
            {
                WritePurchase(2, new List<PurchaseLine>
                {
                    new() { ProductIndex = 7, Qty = 20, ExpiryDays = -48, Capture = "expired2" }
                }, daysAgo, payNow: false);
            }

            if (daysAgo == 8)
            {
                // Twenty days of shelf life left: inside the counter's one-month guard, so it is never
                // sold - and it goes back to the company two days later as a near-expiry lot.
                WritePurchase(2, new List<PurchaseLine>
                {
                    new() { ProductIndex = 12, Qty = 10, ExpiryDays = 20, Capture = "near" }
                }, daysAgo, payNow: false);
            }
        }

        private void RestockIfDeliveryDay(int daysAgo)
        {
            // One agency a day, Monday to Saturday: the shop knows who comes on which morning, which
            // is exactly what the rep's visit day is for. Sunday is closed to deliveries.
            var supplierIndex = DateTime.Today.AddDays(-daysAgo).DayOfWeek switch
            {
                DayOfWeek.Monday => 0,
                DayOfWeek.Tuesday => 1,
                DayOfWeek.Wednesday => 2,
                DayOfWeek.Thursday => 3,
                DayOfWeek.Friday => 4,
                DayOfWeek.Saturday => 5,
                _ => -1
            };

            if (supplierIndex < 0)
            {
                return;
            }

            var lines = new List<PurchaseLine>();

            for (var index = 0; index < Products.Length; index++)
            {
                var product = Products[index];

                if (product.Supplier != supplierIndex || index == SoldOutProduct)
                {
                    continue;
                }

                // Buy what the last week actually used, and never less than twice the reorder level -
                // the same instinct the reorder pad is there to support.
                var target = Math.Max(product.Reorder * 2.0, _soldSinceRestock[index] * 2.4);

                var missing = target - _products[index].Shelf;

                if (missing <= 0)
                {
                    continue;
                }

                var step = product.Typical >= 10 ? 10.0 : 1.0;
                var qty = Math.Ceiling(missing / step) * step;

                if (qty < step)
                {
                    qty = step;
                }

                lines.Add(new PurchaseLine
                {
                    ProductIndex = index, Qty = qty, ExpiryDays = 300 + _rng.Next(420)
                });
            }

            if (lines.Count > 0)
            {
                WritePurchase(supplierIndex, lines, daysAgo, payNow: _rng.Next(100) < 70);
            }
        }

