        private int PickCustomer()
        {
            if (_rng.Next(100) >= 38)
            {
                return -1;
            }

            var roll = _rng.Next(_totalWeight);

            for (var index = 0; index < Customers.Length; index++)
            {
                roll -= Customers[index].Slips;

                if (roll < 0)
                {
                    return index;
                }
            }

            return -1;
        }

        private string PickMethod(int customerIndex)
        {
            var roll = _rng.Next(100);

            if (roll < 60)
            {
                return "cash";
            }

            if (roll < 73)
            {
                return "online";
            }

            if (roll < 84)
            {
                return "card";
            }

            if (roll < 96)
            {
                return customerIndex >= 0 ? "credit" : "cash";
            }

            return customerIndex >= 0 ? "split" : "card";
        }

        private int PickDoctor(int customerIndex)
        {
            if (customerIndex >= 0
                && string.Equals(Customers[customerIndex].Category, "doctor", StringComparison.OrdinalIgnoreCase))
            {
                return customerIndex;
            }

            if (_doctorIndexes.Count == 0 || _rng.Next(100) >= 8)
            {
                return -1;
            }

            return _doctorIndexes[_rng.Next(_doctorIndexes.Count)];
        }

        private List<Pick> PickLines(int daysAgo)
        {
            var wanted = _rng.Next(100) switch
            {
                < 45 => 1,
                < 75 => 2,
                < 92 => 3,
                _ => 4
            };

            var picks = new List<Pick>();
            var used = new HashSet<int>();

            for (var attempt = 0; attempt < 24 && picks.Count < wanted; attempt++)
            {
                var index = PickProduct();

                if (!used.Add(index))
                {
                    continue;
                }

                var seed = Products[index];
                var qty = seed.Typical >= 10 ? seed.Typical * (1 + _rng.Next(2)) : seed.Typical;

                var batch = ChooseBatch(_products[index], qty, daysAgo);

                if (batch is null)
                {
                    qty = seed.Typical;
                    batch = ChooseBatch(_products[index], qty, daysAgo);
                }

                if (batch is null)
                {
                    continue;
                }

                picks.Add(new Pick { ProductIndex = index, Qty = qty, Batch = batch });
            }

            return picks;
        }

        private int PickProduct()
        {
            var roll = _rng.Next(_totalWeight);

            for (var index = 0; index < Products.Length; index++)
            {
                roll -= Products[index].Weight;

                if (roll < 0)
                {
                    return index;
                }
            }

            return 0;
        }

        /// <summary>
        /// First expiry, first out - and never a batch that is inside its last month.
        ///
        /// The date is `daysAgo - 30`, not `daysAgo + 30`: at a day that is `daysAgo` days in the past,
        /// today is `Day(daysAgo)`, and "a month of shelf life left" means a day **later** than that -
        /// `Day(daysAgo - 30)`. Getting the sign wrong here let the sample sell medicine that was about
        /// to expire, which is the one thing a pharmacy demo must never teach.
        /// </summary>
        private BatchState? ChooseBatch(ProductState product, double qty, int daysAgo)
        {
            var earliest = Day(daysAgo - 30);
            BatchState? best = null;

            foreach (var batch in product.Batches)
            {
                if (batch.Qty + 0.0005 < qty)
                {
                    continue;
                }

                if (string.CompareOrdinal(batch.Expiry, earliest) < 0)
                {
                    continue;
                }

                if (best is null || string.CompareOrdinal(batch.Expiry, best.Expiry) < 0)
                {
                    best = batch;
                }
            }

            return best;
        }

        private void DebitBatch(int productIndex, int batchId, double qty)
        {
            foreach (var batch in _products[productIndex].Batches)
            {
                if (batch.Id == batchId)
                {
                    batch.Qty -= qty;
                    return;
                }
            }
        }

        private static long PriceFor(ProductSeed product, string tier) => tier switch
        {
            "vip" => product.Vip > 0 ? product.Vip : product.Retail,
            "doctor" => product.Doctor > 0 ? product.Doctor : product.Retail,
            _ => product.Retail
        };

