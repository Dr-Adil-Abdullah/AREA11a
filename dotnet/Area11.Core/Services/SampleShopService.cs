            _customerIds = customerIds;
            _productIds = productIds;
            _roundStep = settings.GetInt("bill.roundTo", 10);

            foreach (var product in Products)
            {
                _totalWeight += product.Weight;
            }

            // One state per product, in the same order as `Products`, because every other method
            // addresses a medicine by its position in that table (`SoldOutProduct`, the story beats,
            // the bill generator). This loop used to live inside the customer loop below, so only the
            // first twenty medicines ever got a state - and the demo threw on the twenty-first sale.
            for (var index = 0; index < Products.Length; index++)
            {
                _products.Add(new ProductState { Index = index, Id = productIds[index] });
            }

            for (var index = 0; index < Customers.Length; index++)
            {
                _customers.Add(new CustomerState
                {
                    Index = index,
                    Id = customerIds[index],
                    Name = Customers[index].Name,
                    Category = Customers[index].Category,
                    Balance = Customers[index].OpeningPaisa
                });

                if (string.Equals(Customers[index].Category, "doctor", StringComparison.OrdinalIgnoreCase))
                {
                    _doctorIndexes.Add(index);
                }
            }
        }

        public Counts Execute()
        {
            WriteCustomFields();
            WritePackBarcodes();
            WriteOpeningPurchase();

            for (var day = HistoryDays; day >= 0; day--)
            {
                WriteDay(day);
            }

            SellTheLastStock();
            WriteProvisionalReturns();
            WriteHeldCarts();
            WriteBalances();
            AdvanceCounters();
            WriteAuditTrail();

