/// <summary>
/// The sample shop (F-53, D-69, D-74): one button that fills a new Area11 with **two and a half
/// months of one small pharmacy** - 44 medicines across 14 shelves, sixteen companies with their
/// medical reps, six suppliers, twenty customers (two clinics, three doctors), about seven hundred
/// bills at the counter, khata running from before Area11, collections, returns, write-offs, a
/// supplier return, two stock-takes, seventy-two drawers opened and counted, rent, salaries, the
/// electricity bill, the chai, the fan that was repaired - and today's shift still open.
///
/// Why this exists: a new shop is an empty program. Every screen says "nothing here", and the owner
/// cannot tell a page that works from a page that has nothing to show. A *day* of sample data answers
/// "does the bill print?"; **two months** of it answers the questions the owner actually asks at the
/// end of a quarter - what did I sell last month, who still owes me, which medicine is not moving,
/// is the drawer short? A report with three bills in it tells nobody anything.
///
/// Why it is so careful about *where* it runs: this is the only action that writes into every table at
/// once. It refuses a database that already has bills (a real shop must never receive demo money), and
/// it writes in ONE transaction, so a half-filled shop can never exist. Nothing here deletes a row.
///
/// The money is real money on a screen, so every row is generated by the same rules the counter uses:
/// prices from the owner's three tiers, the round-down-with-cost-guard rule from Settings, one batch
/// per sale line, a movement for every unit, and the drawer rebuilt from the payments of the day.
/// </summary>
public sealed class SampleShopService
{
