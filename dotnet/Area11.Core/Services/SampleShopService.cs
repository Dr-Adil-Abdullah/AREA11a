        private void MaybeReturn(int daysAgo)
        {
            if (_bills.Count < 25 || _rng.Next(100) >= 30)
            {
                return;
            }

            var candidates = new List<(Bill Bill, BillLine Line)>();

            foreach (var bill in _bills)
            {
                if (bill.DaysAgo <= daysAgo + 2)
                {
                    continue;
                }

                foreach (var line in bill.Lines)
                {
                    if (line.Qty - line.Returned >= 1)
                    {
                        candidates.Add((bill, line));
                    }
                }
            }

            if (candidates.Count == 0)
            {
                return;
            }

            var pick = candidates[_rng.Next(candidates.Count)];
            var available = pick.Line.Qty - pick.Line.Returned;
            var qty = Math.Min(available, pick.Line.Qty >= 2 ? 2.0 : 1.0);
            var refund = Calc.Round(pick.Line.Price * qty);
            var restock = _rng.Next(100) < 72;

            // A refund on a khata bill first takes money off the khata; only the rest leaves the drawer.
            var credit = Math.Min(refund, pick.Bill.DueNow);
            var cash = refund - credit;
            var stamp = Stamp(daysAgo, 17, 20);

            _returns++;

            var code = Code(_settings, "bill.returnPrefix", _returns);
            string? qcode = null;

            if (!restock)
            {
                _quarantines++;
                qcode = Code(_settings, "bill.quarantinePrefix", _quarantines);
            }

            var returnId = Insert(@"
INSERT INTO sale_returns(date, sale_id, sale_item_id, product_id, batch_id, qty_base, refund_paisa, restock,
                         reason, user_id, created_at, qcode, disposition, qty_entered, unit_sold, note,
                         cash_refund_paisa, credit_reduced_paisa, code)
VALUES(@date, @saleId, @itemId, @productId, @batchId, @qty, @refund, @restock,
       @reason, @userId, @at, @qcode, @disposition, @qty, 'base', @note,
       @cash, @credit, @code);",
                new
                {
                    date = stamp,
                    saleId = pick.Bill.Id,
                    itemId = pick.Line.ItemId,
                    productId = _productIds[pick.Line.ProductIndex],
                    batchId = pick.Line.BatchId,
                    qty,
                    refund,
                    restock = restock ? 1 : 0,
                    reason = ReturnReasons[_rng.Next(ReturnReasons.Length)],
                    userId = _user.Id,
                    at = stamp,
                    qcode,
                    disposition = restock ? "restocked" : "quarantine",
                    note = restock ? "Back on the shelf" : "Kept aside until the owner decides",
                    cash,
                    credit,
                    code
                });

            // Only goods that went back on the shelf move the stock. A quarantine return is set aside
            // and is NOT on the shelf - exactly how ReturnService behaves (U-32).
            if (restock)
            {
                WriteMovement(pick.Line.ProductIndex, pick.Line.BatchId, "return_in", qty, "return", returnId,
                    code, "Returned to the shelf", stamp);

                AddBatchStock(pick.Line.ProductIndex, pick.Line.BatchId, qty);
            }

            pick.Line.Returned += qty;
            pick.Bill.DueNow -= credit;
            _cashOut += cash;

            if (credit > 0 && pick.Bill.CustomerIndex >= 0)
            {
                _customers[pick.Bill.CustomerIndex].Balance -= credit;
            }
        }

        private static readonly string[] ReturnReasons =
        {
            "Customer changed their mind",
            "Doctor changed the medicine",
            "Strip was damaged in the bag",
            "Wrong medicine was given",
            "Patient did not need it",
            "Bottle leaked in the bag",
            "Duplicate bill - the customer bought it twice",
            "Expiry date too close"
        };

