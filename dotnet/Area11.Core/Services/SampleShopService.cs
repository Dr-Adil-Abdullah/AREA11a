        private void WriteStockTake(int daysAgo, string note)
        {
            _stockTakes++;

            var code = Code(_settings, "bill.stockTakePrefix", _stockTakes);
            var date = Day(daysAgo);
            var counted = Stamp(daysAgo, 19, 30);
            var applied = Stamp(daysAgo, 20, 0);

            var sessionId = Insert(@"
INSERT INTO stock_takes(code, date, status, room, category_id, note, items_count, diff_count, short_paisa,
                        extra_paisa, user_id, applied_at, applied_by, created_at)
