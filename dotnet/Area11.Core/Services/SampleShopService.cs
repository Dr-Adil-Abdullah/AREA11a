            // One shelf short and one shelf long: the page shows both colours. The book quantity is
            // the batch's own quantity, so the count can never disagree with the shelf it counted.
            WriteStockTakeLine(sessionId, 0, 3, -3, daysAgo, code, counted, applied);
            WriteStockTakeLine(sessionId, 20, 2, 2, daysAgo, code, counted, applied);

            // The session's own totals are then rebuilt from its two lines, so the header can never
            // disagree with the rows underneath it.
            _db.Execute(_connection, @"
UPDATE stock_takes
SET items_count = (SELECT COUNT(1) FROM stock_take_items WHERE stock_take_id = @id),
    diff_count = (SELECT COUNT(1) FROM stock_take_items WHERE stock_take_id = @id AND diff_qty_base <> 0),
    short_paisa = IFNULL((SELECT SUM(-value_paisa) FROM stock_take_items WHERE stock_take_id = @id AND diff_qty_base < 0), 0),
    extra_paisa = IFNULL((SELECT SUM(value_paisa) FROM stock_take_items WHERE stock_take_id = @id AND diff_qty_base > 0), 0)
WHERE id = @id;", new { id = sessionId });
        }

        private void WriteStockTakeLine(int sessionId, int productIndex, int batchNumber, double difference,
            int daysAgo, string code, string counted, string applied)
        {
            var product = _products[productIndex];

            if (batchNumber >= product.Batches.Count)
            {
                return;
            }

            var batch = product.Batches[batchNumber];

            if (batch.Qty < 3)
            {
                return;
            }

            var systemQty = Math.Floor(batch.Qty);
            var countedQty = systemQty + difference;
            var diff = difference;

            Insert(@"
INSERT INTO stock_take_items(stock_take_id, product_id, batch_id, system_qty_base, counted_qty_base, unit_entered,
                             qty_entered, diff_qty_base, value_paisa, created_at, system_cost_paisa, counted_by,
                             counted_at, note)
VALUES(@sessionId, @productId, @batchId, @system, @counted, 'base', @counted, @diff, @value, @at, @cost, @userId,
       @at, @note);",
                new
                {
                    sessionId,
                    productId = _productIds[productIndex],
                    batchId = batch.Id,
                    system = systemQty,
                    counted = countedQty,
                    diff,
                    value = Calc.Round(diff * Products[productIndex].Cost),
                    at = counted,
                    cost = Products[productIndex].Cost,
                    userId = _user.Id,
                    note = diff < 0 ? "Fewer on the shelf" : "More than the book"
                });

            WriteMovement(productIndex, batch.Id, "adjust", diff, "stock_take", sessionId, code,
                "Stock-take difference", applied);

            AddBatchStock(productIndex, batch.Id, diff);
        }

