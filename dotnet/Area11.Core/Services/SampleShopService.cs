        private void WriteBalances()
        {
            // What each khata customer still owes: what he carried in, plus what the bills left on the
            // khata, minus what a return took off it, minus the money he brought back.
            _db.Execute(_connection, @"
UPDATE customers
SET balance_paisa = MAX(0, opening_balance_paisa
    + IFNULL((SELECT SUM(s.due_paisa) FROM sales s WHERE s.customer_id = customers.id AND s.due_paisa > 0), 0)
    - IFNULL((SELECT SUM(r.credit_reduced_paisa) FROM sale_returns r
              JOIN sales s2 ON s2.id = r.sale_id
              WHERE s2.customer_id = customers.id), 0)
    - IFNULL((SELECT SUM(p.amount_paisa) FROM payments p
              WHERE p.customer_id = customers.id AND p.sale_id IS NULL AND p.purchase_id IS NULL), 0))
WHERE id > 0;");

            _db.Execute(_connection, @"
UPDATE suppliers
SET balance_paisa = opening_balance_paisa
    + IFNULL((SELECT SUM(p.due_paisa) FROM purchases p
              WHERE p.supplier_id = suppliers.id AND p.due_paisa > 0), 0)
WHERE id > 0;");

            // Stock on the shelf IS the sum of the movements: bought + returned - sold - written off.
            // Doing it in one statement at the end is what keeps the sample shop's shelves and its
            // movement history in agreement, which is the property the tests pin.
            _db.Execute(_connection, @"
UPDATE batches
SET qty_base = IFNULL((SELECT SUM(m.qty_base) FROM stock_movements m WHERE m.batch_id = batches.id), 0)
WHERE id > 0;");
        }

        /// <summary>
        /// Moves every document counter past the sample, so the first real bill is the one after the
        /// last demo bill and never collides with it (the unique index on `sales.code` would refuse).
        /// </summary>
        private void AdvanceCounters()
        {
            var counters = new Dictionary<string, long>
            {
                ["bill.nextSaleNo"] = _sales + 1,
                ["bill.nextPurchaseNo"] = _purchases + 1,
                ["bill.nextReturnNo"] = _returns + 1,
                ["bill.nextProvisionalNo"] = _provisionals + 1,
                ["bill.nextSupplierReturnNo"] = _supplierReturns + 1,
                ["bill.nextStockTakeNo"] = _stockTakes + 1,
                ["bill.nextQuarantineNo"] = _quarantines + 1,
                ["bill.nextHoldNo"] = _holds + 1
            };

            foreach (var counter in counters)
            {
                _settings.WriteCounter(_connection, counter.Key, counter.Value);
            }
        }

