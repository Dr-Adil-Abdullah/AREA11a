        private void CollectKhata(int daysAgo)
        {
            if (_rng.Next(100) >= 34)
            {
                return;
            }

            var payers = new List<CustomerState>();

            foreach (var customer in _customers)
            {
                if (customer.Balance >= 50000)
                {
                    payers.Add(customer);
                }
            }

            if (payers.Count == 0)
            {
                return;
            }

            var payer = payers[_rng.Next(payers.Count)];
            var amount = Math.Min(payer.Balance, 50000L + _rng.Next(12) * 50000L);
            var method = _rng.Next(100) < 80 ? "cash" : "online";
            var stamp = Stamp(daysAgo, 18, 20);

            Insert(@"
