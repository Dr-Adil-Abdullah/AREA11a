        /// <summary>
        /// Pays an old bill. Most distributors are paid by bank transfer today, so the drawer is not
        /// emptied by stock - the one cash supplier is paid from the till, and only when it can afford it.
        /// </summary>
        private void PayPurchase(PurchaseRecord record, long amount, int daysAgo, string method)
        {
            amount = Math.Min(amount, record.Total - record.Paid);

            if (amount <= 0)
            {
                return;
            }

            if (string.Equals(method, "cash", StringComparison.Ordinal) && !CanSpend(amount))
            {
                method = "online";
            }

            var stamp = Stamp(daysAgo, 16, 40);

            Insert(@"
INSERT INTO payments(date, method, amount_paisa, ref, sale_id, purchase_id, customer_id, supplier_id, user_id, note)
VALUES(@date, @method, @amount, @ref, NULL, @purchaseId, NULL, @supplierId, @userId, @note);",
                new
                {
                    date = stamp,
                    method,
                    amount,
                    @ref = "PINV-" + record.Id.ToString(CultureInfo.InvariantCulture),
                    purchaseId = record.Id,
                    supplierId = _supplierIds[record.SupplierIndex],
                    userId = _user.Id,
                    note = "Paid the supplier"
                });

            record.Paid += amount;

            _db.Execute(_connection,
                "UPDATE purchases SET paid_paisa = @paid, due_paisa = @due WHERE id = @id;",
                new { paid = record.Paid, due = record.Total - record.Paid, id = record.Id });

            if (string.Equals(method, "cash", StringComparison.Ordinal))
            {
                _cashOut += amount;
            }
        }

        private void SettleOldPurchases(int daysAgo)
        {
            foreach (var record in _openPurchases)
            {
                if (record.Paid >= record.Total || daysAgo > record.DaysAgo - 3)
                {
                    continue;
                }

                // Some bills are paid within the week, some wait for the owner to check the delivery.
                if (_rng.Next(100) < 55)
                {
                    PayPurchase(record, record.Total - record.Paid, daysAgo,
                        record.SupplierIndex == 3 ? "cash" : "online");
                }
            }
        }

