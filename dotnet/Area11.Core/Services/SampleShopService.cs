        private void WriteBills(int daysAgo)
        {
            var lastHour = daysAgo == 0 ? Math.Clamp(DateTime.Now.Hour, 10, 20) : 20;

            if (lastHour <= 9)
            {
                return;
            }

            var count = BillCount(daysAgo);

            for (var bill = 0; bill < count; bill++)
            {
                WriteBill(daysAgo, 9 + _rng.Next(lastHour - 9 + 1), _rng.Next(60));
            }
        }

        private int BillCount(int daysAgo)
        {
            var day = DateTime.Today.AddDays(-daysAgo).DayOfWeek;

            var count = day switch
            {
                DayOfWeek.Sunday => 5 + _rng.Next(3),
                DayOfWeek.Friday => 11 + _rng.Next(5),
                DayOfWeek.Saturday => 9 + _rng.Next(4),
                _ => 8 + _rng.Next(5)
            };

            // Today is still going on: half a day of bills, and the drawer still open.
            return daysAgo == 0 ? Math.Max(2, count / 2) : count;
        }

        private void WriteBill(int daysAgo, int hour, int minute)
        {
            var stamp = Stamp(daysAgo, hour, minute);
            var customerIndex = PickCustomer();
            var method = PickMethod(customerIndex);
            var doctorIndex = PickDoctor(customerIndex);
            var picks = PickLines(daysAgo);

            if (picks.Count == 0)
            {
                return;
            }

            var tier = customerIndex >= 0 ? Customers[customerIndex].Category : "normal";

            long subtotal = 0;
            long costTotal = 0;

            var lines = new List<BillLine>();

            foreach (var pick in picks)
            {
                var product = Products[pick.ProductIndex];
                var price = PriceFor(product, tier);
                var total = Calc.Round(price * pick.Qty);

                subtotal += total;
                costTotal += Calc.Round(product.Cost * pick.Qty);

                lines.Add(new BillLine
                {
                    ProductIndex = pick.ProductIndex,
                    BatchId = pick.Batch.Id,
                    Qty = pick.Qty,
                    Price = price,
                    Total = total
                });
            }

            // The shop rounds DOWN to the nearest ten rupees, never below cost - the same rule the
            // counter uses (Z-03), so the sample bills obey the owner's own settings.
            var billTotal = Money.RoundDownWithCostGuard(subtotal, costTotal, _roundStep);
            var roundOff = subtotal - billTotal;

            long paid;

            if (string.Equals(method, "credit", StringComparison.Ordinal))
            {
                // A khata bill: usually nothing at the counter, sometimes half now and half later.
                paid = _rng.Next(100) < 45 ? billTotal / 2000 * 1000 : 0;
            }
            else
            {
                paid = billTotal;
            }

            var due = billTotal - paid;
            var status = due <= 0 ? "paid" : paid <= 0 ? "credit" : "partial";

            _sales++;

            var code = Code(_settings, "bill.salePrefix", _sales);

            var saleId = Insert(@"
INSERT INTO sales(code, date, customer_id, user_id, subtotal_paisa, discount_paisa, tax_paisa, round_off_paisa,
                  total_paisa, paid_paisa, due_paisa, status, payment_method, notes, created_at, doctor_id)
VALUES(@code, @date, @customer, @userId, @subtotal, 0, 0, @roundOff,
       @total, @paid, @due, @status, @method, @notes, @at, @doctor);",
                new
                {
                    code,
                    date = stamp,
                    customer = customerIndex >= 0 ? _customerIds[customerIndex] : (int?)null,
                    userId = _user.Id,
                    subtotal,
                    roundOff,
                    total = billTotal,
                    paid,
                    due,
                    status,
                    method,
                    notes = doctorIndex >= 0 ? "On prescription" : "Sample bill",
                    at = stamp,
                    doctor = doctorIndex >= 0 ? _customerIds[doctorIndex] : (int?)null
                });

            var bill = new Bill
            {
                Id = saleId,
                Code = code,
                DaysAgo = daysAgo,
                CustomerIndex = customerIndex,
                DueNow = due
            };

            foreach (var line in lines)
            {
                var product = Products[line.ProductIndex];

                line.ItemId = Insert(@"
INSERT INTO sale_items(sale_id, product_id, batch_id, name_snapshot, qty_base, unit_sold, qty_entered,
                       unit_price_paisa, discount_paisa, line_total_paisa, cost_paisa_at_sale)
VALUES(@saleId, @productId, @batchId, @name, @qty, 'base', @qty, @price, 0, @total, @cost);",
                    new
                    {
                        saleId,
                        productId = _productIds[line.ProductIndex],
                        batchId = line.BatchId,
                        name = product.Name,
                        qty = line.Qty,
                        price = line.Price,
                        total = line.Total,
                        cost = product.Cost
                    });

                WriteMovement(line.ProductIndex, line.BatchId, "sale", -line.Qty, "sale", saleId, code,
                    "Sold", stamp);

                DebitBatch(line.ProductIndex, line.BatchId, line.Qty);
                _soldSinceRestock[line.ProductIndex] += line.Qty;

                bill.Lines.Add(line);
            }

            WriteSalePayments(saleId, method, paid, stamp);

            if (customerIndex >= 0 && due > 0)
            {
                _customers[customerIndex].Balance += due;
            }

            _bills.Add(bill);
        }

