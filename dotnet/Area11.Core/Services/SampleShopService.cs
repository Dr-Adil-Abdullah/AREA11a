VALUES(@productId, @batchId, @type, @qty, @refType, @refId, @refCode, @note, @userId, @at);",
                new
                {
                    productId = _productIds[productIndex],
                    batchId,
                    type,
                    qty,
                    refType,
                    refId,
                    refCode,
                    note,
                    userId = _user.Id,
                    at
                });
        }

        private int Insert(string sql, object row)
        {
            _db.Execute(_connection, sql, row);
            return (int)_db.NextId(_connection);
        }

